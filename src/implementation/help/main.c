
#include "interface/help/main.h"

#include <stdio.h>

static void _print_help(void) {
        printf(
            "oopdbms - Object-Oriented Database Management System\n"
            "\n"
            "USAGE\n"
            "  oopdbms '<statement>'\n"
            "  oopdbms <statement split into arguments>\n"
            "  oopdbms\n"
            "\n"
            "CLASSES\n"
            "  CREATE CLASS <name> [EXTENDS <class>] "
            "[IMPLEMENTS <interface>[, ...]] (<field> <type>[, ...])\n"
            "  DROP CLASS <name>\n"
            "  ALTER CLASS <name> ADD FIELD <field> <type>\n"
            "  ALTER CLASS <name> DROP FIELD <field>\n"
            "  ALTER CLASS <name> RENAME FIELD <old> <new>\n"
            "  ALTER CLASS <name> RENAME <new>\n"
            "  ALTER CLASS <name> EXTENDS <class>\n"
            "  ALTER CLASS <name> IMPLEMENTS <interface>\n"
            "\n"
            "INTERFACES\n"
            "  CREATE INTERFACE <name> (<field> <type>[, ...])\n"
            "  DROP INTERFACE <name>\n"
            "\n"
            "FUNCTIONS\n"
            "  CREATE FUNCTION <class>.<name> "
            "(<arg> <type>[, ...]) RETURNS <type> AS <expression>\n"
            "  DROP FUNCTION <class>.<name>\n"
            "  CALL <class>.<name> (<value>[, ...]) ON <id>\n"
            "\n"
            "OBJECTS\n"
            "  NEW <class> (<field> = <value>[, ...])\n"
            "  FIND <class> [WHERE <condition>]\n"
            "  SET <class> <id> (<field> = <value>[, ...])\n"
            "  DELETE <class> <id>\n"
            "\n"
            "INFORMATION\n"
            "  LIST CLASSES\n"
            "  LIST INTERFACES\n"
            "  DESCRIBE <class>\n"
            "\n"
            "TYPES\n"
            "  integer          Whole numbers\n"
            "  float            Decimal numbers\n"
            "  text             Text values\n"
            "  bool             true or false\n"
            "  pointer <class>  Reference to an object of a class\n"
            "\n"
            "EXPRESSIONS\n"
            "  Operators: +  -  *  /\n"
            "  Comparisons: =  !=  <  <=  >  >=\n"
            "  Use parentheses to group expressions.\n"
            "  Text values can use single or double quotes.\n"
            "\n"
            "EXAMPLES\n"
            "  CREATE INTERFACE Named (name text)\n"
            "  CREATE CLASS Person IMPLEMENTS Named "
            "(name text, age integer)\n"
            "  CREATE CLASS Employee EXTENDS Person (salary float)\n"
            "  NEW Person (name = \"Ada Lovelace\", age = 36)\n"
            "  FIND Person WHERE age >= 18\n"
            "  SET Person 1 (age = 37)\n"
            "  DELETE Person 1\n"
            "  LIST CLASSES\n"
            "  DESCRIBE Person\n"
            "\n"
            "DATABASE\n"
            "  Default file: database.oopdb\n"
            "  Set OOPDB to use a different database file:\n"
            "    OOPDB=/path/to/database.oopdb oopdbms 'FIND Person'\n"
            "\n"
            "NOTES\n"
            "  Commands and keywords are case-sensitive.\n"
            "  Quote the entire statement when passing it as one argument.\n"
            "  The database file is checked before a statement is processed.\n"
            "  Statement execution is not implemented yet.\n"
            "\n"
            "BUILD AND TEST\n"
            "  make        Build the project\n"
            "  make test   Run tests\n"
            "  make clean  Remove build artifacts\n"
            "\n"
            "For detailed documentation, see README.md.\n");
}

void i_print_help(void) { _print_help(); }
